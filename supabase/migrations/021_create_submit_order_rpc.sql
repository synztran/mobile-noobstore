-- ─── Migration 021: Atomic submit_order RPC ──────────────────────────────────
-- Replaces the multi-step checkout flow (validate_and_deduct_stock + separate
-- INSERT calls) with a single PL/pgSQL function that:
--
--   1. Acquires row-level locks (SELECT … FOR UPDATE) on every product /
--      component variant being purchased — preventing concurrent transactions
--      from reading stale stock values.
--   2. Validates stock across all items before touching anything.
--   3. Deducts stock.
--   4. Creates the order, order_items, and order_item_components rows.
--
-- Because all four phases execute inside one implicit PL/pgSQL transaction,
-- either EVERYTHING commits or NOTHING does.  A server crash after stock
-- deduction will never leave an order-less stock hole.
--
-- Input parameters:
--   p_order_id      UUID  — generated by the API layer (crypto.randomUUID)
--   p_user_id       UUID  — nullable for guest checkout
--   p_order_number  TEXT  — human-readable e.g. "ORD-LK4J2-XY9Z"
--   p_total_price   NUMERIC
--   p_shipping_cost NUMERIC
--   p_items         JSONB — array of:
--     {
--       "product_id":   "uuid",
--       "product_name": "text",
--       "unit_price":   number,
--       "thumbnail":    "text | null",
--       "quantity":     number,
--       "components": [   -- present for kit products
--         {
--           "variant_id":       "uuid",
--           "variant_name":     "text",
--           "component_group":  "text",
--           "price_adjustment": number,
--           "thumbnail":        "text | null",
--           "quantity":         number   -- units per kit (usually 1)
--         }
--       ]
--     }
--
-- Returns:
--   { "order_id": "uuid", "order_number": "text", "status": "pending" }
--   or raises an EXCEPTION (transaction rolls back automatically).
-- ─────────────────────────────────────────────────────────────────────────────

CREATE OR REPLACE FUNCTION public.submit_order(
  p_order_id      UUID,
  p_user_id       UUID,
  p_order_number  TEXT,
  p_total_price   NUMERIC,
  p_shipping_cost NUMERIC,
  p_items         JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
AS $$
DECLARE
  v_item          JSONB;
  v_comp          JSONB;
  v_parent_qty    INTEGER;
  v_comp_qty      INTEGER;
  v_total_req     INTEGER;
  v_avail         INTEGER;
  v_item_name     TEXT;
  v_product_type  TEXT;
  v_order_item_id UUID;
BEGIN

  -- ── Phase 1: Lock rows & validate stock ──────────────────────────────────
  -- FOR UPDATE acquires row-level locks so concurrent transactions must wait,
  -- eliminating the TOCTOU race condition.

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items) LOOP
    v_parent_qty := (v_item->>'quantity')::INTEGER;

    SELECT p.stock_quantity, p.name, p.product_type
      INTO v_avail, v_item_name, v_product_type
      FROM public.products p
     WHERE p.id = (v_item->>'product_id')::TEXT
       FOR UPDATE;                           -- ← lock the product row

    IF v_avail IS NULL THEN
      RAISE EXCEPTION 'Sản phẩm không tồn tại: %', v_item->>'product_id';
    END IF;

    -- Non-kit: parent product carries its own stock
    IF COALESCE(v_product_type, 'standard') <> 'kit' AND v_avail < v_parent_qty THEN
      RAISE EXCEPTION 'Hết hàng: "%" — còn %, yêu cầu %',
        v_item_name, v_avail, v_parent_qty;
    END IF;

    -- Kit / component variants: lock + validate each component
    FOR v_comp IN SELECT * FROM jsonb_array_elements(COALESCE(v_item->'components', '[]'::JSONB)) LOOP
      v_comp_qty  := COALESCE((v_comp->>'quantity')::INTEGER, 1);
      v_total_req := v_parent_qty * v_comp_qty;

      SELECT pv.stock_quantity
        INTO v_avail
        FROM public.product_variants pv
       WHERE pv.id = (v_comp->>'variant_id')::TEXT
         FOR UPDATE;                         -- ← lock the variant row

      IF v_avail IS NULL THEN
        RAISE EXCEPTION 'Phiên bản sản phẩm không tồn tại: %', v_comp->>'variant_id';
      END IF;

      IF v_avail < v_total_req THEN
        SELECT p.name || ' — ' || pv.variant_name
          INTO v_item_name
          FROM public.product_variants pv
          JOIN public.products p ON p.id = pv.product_id
         WHERE pv.id = (v_comp->>'variant_id')::TEXT;

        RAISE EXCEPTION 'Hết hàng: "%" — còn %, yêu cầu %',
          COALESCE(v_item_name, v_comp->>'variant_id'), v_avail, v_total_req;
      END IF;
    END LOOP;
  END LOOP;

  -- ── Phase 2: Deduct stock ─────────────────────────────────────────────────
  -- Rows are already locked; no concurrent transaction can slip in between
  -- the validation above and these UPDATEs.

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items) LOOP
    v_parent_qty := (v_item->>'quantity')::INTEGER;

    SELECT p.product_type
      INTO v_product_type
      FROM public.products p
     WHERE p.id = (v_item->>'product_id')::TEXT;

    IF COALESCE(v_product_type, 'standard') <> 'kit' THEN
      UPDATE public.products
         SET stock_quantity = stock_quantity - v_parent_qty
       WHERE id = (v_item->>'product_id')::TEXT;
    END IF;

    FOR v_comp IN SELECT * FROM jsonb_array_elements(COALESCE(v_item->'components', '[]'::JSONB)) LOOP
      v_comp_qty  := COALESCE((v_comp->>'quantity')::INTEGER, 1);
      v_total_req := v_parent_qty * v_comp_qty;

      UPDATE public.product_variants
         SET stock_quantity = stock_quantity - v_total_req
       WHERE id = (v_comp->>'variant_id')::TEXT;
    END LOOP;
  END LOOP;

  -- ── Phase 3: Create order ─────────────────────────────────────────────────

  INSERT INTO public.orders (id, user_id, order_number, status, total_price, shipping_fee)
  VALUES (p_order_id, p_user_id, p_order_number, 'pending', p_total_price, p_shipping_cost);

  -- ── Phase 4: Create order_items + order_item_components ───────────────────

  FOR v_item IN SELECT * FROM jsonb_array_elements(p_items) LOOP
    v_order_item_id := gen_random_uuid();

    INSERT INTO public.order_items (id, order_id, product_id, product_name, unit_price, thumbnail, quantity)
    VALUES (
      v_order_item_id,
      p_order_id,
      v_item->>'product_id',
      v_item->>'product_name',
      (v_item->>'unit_price')::NUMERIC,
      NULLIF(v_item->>'thumbnail', ''),
      (v_item->>'quantity')::INTEGER
    );

    FOR v_comp IN SELECT * FROM jsonb_array_elements(COALESCE(v_item->'components', '[]'::JSONB)) LOOP
      INSERT INTO public.order_item_components (
        order_item_id, variant_id, variant_name, component_group, price_adjustment, thumbnail
      ) VALUES (
        v_order_item_id,
        v_comp->>'variant_id',
        v_comp->>'variant_name',
        v_comp->>'component_group',
        COALESCE((v_comp->>'price_adjustment')::NUMERIC, 0),
        NULLIF(v_comp->>'thumbnail', '')
      );
    END LOOP;
  END LOOP;

  RETURN jsonb_build_object(
    'order_id',     p_order_id::TEXT,
    'order_number', p_order_number,
    'status',       'pending'
  );
END;
$$;

GRANT EXECUTE ON FUNCTION public.submit_order(UUID, UUID, TEXT, NUMERIC, NUMERIC, JSONB)
  TO anon, authenticated;
